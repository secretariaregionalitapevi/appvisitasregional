const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('static/js/music-ministry.js','utf8');
const ratio=source.slice(source.indexOf('  function ratio('),source.indexOf('  function details('));
const sandbox={};vm.createContext(sandbox);vm.runInContext(ratio+';this.ratio=ratio;',sandbox);
const cells=(...states)=>states.map(situacao=>({situacao}));
let html=sandbox.ratio(cells('SEM_REGISTRO','SEM_REGISTRO','SEM_REGISTRO'));
assert.ok(html.includes('zero">0/3'));
html=sandbox.ratio(cells('PRESENTE','SEM_REGISTRO','JUSTIFICOU','SEM_DADOS','CONFERIR','NAO_APLICA'));
assert.ok(html.includes('partial">1/3'));
assert.ok(html.includes('2 encontros pendentes'));
html=sandbox.ratio(cells('SEM_DADOS','CONFERIR'));
assert.ok(html.includes('Sem conferência'));
assert.ok(!html.includes('0/'));
assert.ok(!html.includes('zero'));
html=sandbox.ratio(cells('PRESENTE','PRESENTE'));
assert.ok(html.includes('>2/2'));
assert.ok(!html.includes('zero'));
